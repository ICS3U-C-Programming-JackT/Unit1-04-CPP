#include <iostream>
#include <cmath>  // import the BEST math library (math.h is not updated as much as cmath)

int main() {
    std::cout << "9 + 2 = " << 9+2 << std::endl;
    std::cout << "5 - 7 = " << 5-7 << std::endl;
    std::cout << "16 * 2 = " << 16*2 << std::endl;
    std::cout << "121 / 11 = " << 121/11 << std::endl;
    std::cout << "3 ** 2 = " << pow(3, 2) << std::endl;
    std::cout << "root 225 = " << sqrt(225) << std::endl;
}
